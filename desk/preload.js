const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('desk', {
  defs: () => ipcRenderer.invoke('data:defs'),
  refresh: () => ipcRenderer.invoke('data:refresh'),
  messages: (id) => ipcRenderer.invoke('run:messages', id),
  memoryList: () => ipcRenderer.invoke('memory:list'),
  memoryRead: (slug) => ipcRenderer.invoke('memory:read', slug),
  agentRaw: (slug) => ipcRenderer.invoke('agent:raw', slug),
  agentSave: (slug, payload) => ipcRenderer.invoke('agent:save', slug, payload),
  gmemList: () => ipcRenderer.invoke('gmem:list'),
  fileRead: (p) => ipcRenderer.invoke('file:read', p),
  fileWrite: (p, text) => ipcRenderer.invoke('file:write', p, text),
  paths: () => ipcRenderer.invoke('app:paths'),
  reveal: (p) => ipcRenderer.invoke('app:open', p),
  brokerList: () => ipcRenderer.invoke('broker:list'),
  brokerMessages: (id) => ipcRenderer.invoke('broker:messages', id),
  brainData: (p) => ipcRenderer.invoke('brain:data', p),
  projList: () => ipcRenderer.invoke('proj:list'),
  projAdd: (dir) => ipcRenderer.invoke('proj:add', dir),
  projRemove: (id) => ipcRenderer.invoke('proj:remove', id),
  projRename: (id, n) => ipcRenderer.invoke('proj:rename', id, n),
  cliInfo: () => ipcRenderer.invoke('cli:info'),
  cliOpen: (o) => ipcRenderer.invoke('cli:open', o),
  cliSend: (id, t) => ipcRenderer.invoke('cli:send', id, t),
  cliAnswer: (id, req, d) => ipcRenderer.invoke('cli:answer', id, req, d),
  cliInterrupt: (id) => ipcRenderer.invoke('cli:interrupt', id),
  cliSetMode: (id, m) => ipcRenderer.invoke('cli:setMode', id, m),
  cliSetModel: (id, m) => ipcRenderer.invoke('cli:setModel', id, m),
  cliClose: (id) => ipcRenderer.invoke('cli:close', id),
  pickDir: () => ipcRenderer.invoke('cli:pickDir'),
  commands: () => ipcRenderer.invoke('cli:commands'),
  onCli: (cb) => ipcRenderer.on('cli:event', (_e, m) => cb(m)),
  // convenções de app
  copy: (text) => ipcRenderer.invoke('clipboard:write', text),
  find: (text, opts) => ipcRenderer.send('find:run', text, opts || {}),
  stopFind: () => ipcRenderer.send('find:stop'),
  onFound: (cb) => ipcRenderer.on('find:result', (_e, r) => cb(r)),
  exportSave: (name, text) => ipcRenderer.invoke('export:save', name, text),
  onCommand: (cb) => ipcRenderer.on('cmd', (_e, c) => cb(c)),
});
